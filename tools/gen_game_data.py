"""Generate the editor's game data tables from a dump of the game's RomFS.

    python3 tools/gen_game_data.py /path/to/romfs

The RomFS comes from your own copy of the game (for example Eden: right-click the game, Dump RomFS).
It reads SystemData/WorldList.szs and SystemData/ShineInfo.szs and writes three files under
smo_save_editor/app/game_data/: the kingdom of every purple coin, the scenario numbers of every kingdom,
the story moons (the ones that advance Main scenario) of every kingdom, what each shop item costs, and how
many Power Moons it takes to leave each kingdom, which Power Moons are the ones bought in a shop, in which scenarios each Power Moon can be found, the game's own moon names, the checkpoints, the\ncaptures and the achievement thresholds. Only facts (numbers) are
written, no game assets."""
import importlib.util, json, re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
def load(name):
    spec = importlib.util.spec_from_file_location(name, HERE / f'{name}.py')
    module = importlib.util.module_from_spec(spec); spec.loader.exec_module(module)
    return module

szs, msbt = load('szs'), load('msbt')

root = Path(sys.argv[1]); out = HERE.parent / 'smo_save_editor' / 'app' / 'game_data'
files = szs.sarc(szs.yaz0((root / 'SystemData' / 'WorldList.szs').read_bytes()))
byml = lambda name: szs.byml(files[name])

worlds = byml('WorldListFromDb.byml')          # index = the game's world index
scenarios = byml('WorldList.byml')
coins = byml('CoinCollectList.byml')['Table']
per_world = {e['WorldName']: e['CollectCoinNum'] for e in byml('CollectCoinNum.byml')}

stage_world = {}
for index, world in enumerate(worlds):
    for stage in world['StageList']:
        stage_world.setdefault(stage['name'], index)
world_of = {c['UniqueId']: stage_world[c['StageName']] for c in coins}   # KeyError = a stage we cannot place

# the table must agree with the game's own per-kingdom totals
for index, world in enumerate(worlds):
    have = sum(1 for w in world_of.values() if w == index)
    assert have == per_world[world['WorldName']], (world['WorldName'], have, per_world[world['WorldName']])

ids = sorted(world_of); runs = []; first = prev = ids[0]
for i in ids[1:]:
    if i != prev + 1 or world_of[i] != world_of[prev]:
        runs.append((first, prev, world_of[prev])); first = i
    prev = i
runs.append((first, prev, world_of[prev]))

(out / 'coin_catalog' / 'purple_coins.ts').write_text('''// Which kingdom each purple (regional) coin belongs to, by the UniqueId the save stores.
// Each entry is a run of consecutive IDs of one kingdom: [first ID, last ID, kingdom (game world index)].
//
// Generated by tools/gen_game_data.py from the game's own data: CoinCollectList (every coin and the
// stage it is in) and WorldListFromDb (which stages belong to which kingdom), in SystemData/WorldList.
// The totals match the game's CollectCoinNum for all 17 kingdoms (50 or 100 each, 1000 in all).
export const COIN_RANGES: readonly (readonly [first: number, last: number, kingdom: number])[] = [
''' + ''.join(f'  [{a}, {b}, {w}],\n' for a, b, w in runs) + '];\n')

lines = []
for index, w in enumerate(scenarios):
    balloon = f', balloon: {w["BalloonScenario"]}' if 'BalloonScenario' in w else ''
    lines.append(f'  {{ count: {w["ScenarioNum"]}, clear: {w["ClearMainScenario"]}, afterEnding: {w["AfterEndingScenario"]}, '
                 f'moonRock: {w["MoonRockScenario"]}{balloon}, '
                 f'mainMin: {json.dumps(w["MainQuestInfo"])} }}, // {w["WorldName"]}\n')
(out / 'scenario_catalog').mkdir(exist_ok=True)
(out / 'scenario_catalog' / 'scenarios.ts').write_text('''// The scenarios of each kingdom, by game world index: how many there are (ScenarioNum), and which
// numbers are special. ScenarioNo in the save is one of 1..count, and it decides how the kingdom looks.
//
// Generated by tools/gen_game_data.py from the game's own WorldList (SystemData/WorldList).
export interface ScenarioInfo {
  count: number;
  /** ClearMainScenario: the story of the kingdom is cleared ("world peace"). */
  clear: number;
  /** AfterEndingScenario: after the ending of the game. */
  afterEnding: number;
  /** MoonRockScenario: the Moon Rock is open. */
  moonRock: number;
  /** BalloonScenario: Balloon World; absent in kingdoms that have none. */
  balloon?: number;
  /** MainQuestInfo: the least Main scenario (MainShineNo) each scenario goes with, for scenario 1, 2, ... */
  mainMin: readonly number[];
}

export const SCENARIOS: readonly ScenarioInfo[] = [
''' + ''.join(lines) + '];\n')
shine = szs.sarc(szs.yaz0((root / 'SystemData' / 'ShineInfo.szs').read_bytes()))
story = []
for name in sorted(shine):
    if not name.startswith('ShineList_'): continue
    for m in szs.byml(shine[name])['ShineList']:
        if m['MainScenarioNo'] >= 0:
            story.append((stage_world[m['StageName']], m['MainScenarioNo'], m['UniqueId']))
story.sort()
(out / 'story_catalog' / 'story_moons.ts').write_text('''// The story moons of each kingdom: [kingdom (game world index), Main scenario number, moon UniqueId].
// Main scenario (MainShineNo in the save) counts the story moons done; the moon with number N is the
// objective while Main scenario is N. Several moons can share a number (any of them advances it).
// Cap, Cloud and Mushroom have none in the game's lists.
//
// Generated by tools/gen_game_data.py from the game's ShineList_* tables (SystemData/ShineInfo).
export const STORY_MOONS: readonly (readonly [kingdom: number, scenario: number, moon: number])[] = [
''' + ''.join(f'  [{a}, {b}, {c}],\n' for a, b, c in story) + '];\n')
# What every shop item costs (ItemList): ordinary coins, or the purple coins of the kingdom whose shop sells it.
index_of = {w['WorldName']: i for i, w in enumerate(worlds)}
items = szs.sarc(szs.yaz0((root / 'SystemData' / 'ItemList.szs').read_bytes()))
lists = {'Cap': '/ItemCap', 'Clothes': '/ItemCloth', 'Gift': '/ItemGift', 'Sticker': '/ItemSticker'}
prices = []
for e in szs.byml(items['ItemList.byml']):
    if e['ItemType'] not in lists: continue
    purple = e['CoinType'] == 'Collect'
    prices.append((lists[e['ItemType']], e['ItemName'], int(purple), e['Price'],
                   index_of[e['StoreName']] if 'StoreName' in e else -1,
                   index_of[e['ClearWorld']] if 'ClearWorld' in e else -1, e.get('MoonNum', 0)))
for p in prices:   # purple coins are always spent in the kingdom of the shop, per kingdom they sum to its coin total
    assert (p[2] == 1) == (p[4] >= 0), p
(out / 'shop_catalog').mkdir(exist_ok=True)
(out / 'shop_catalog' / 'shop_prices.ts').write_text('''// What the shop items cost, by list (the save's /ItemCap, /ItemCloth, /ItemGift, /ItemSticker) and
// internal name: [list, name, purple, price, shop kingdom, kingdom to clear first, Power Moons needed].
// purple = 1 means the price is in the purple coins of the shop's kingdom (game world index, -1 for the
// ordinary-coin items), purple = 0 means ordinary coins. "Kingdom to clear first" is -1 when there is none.
//
// Generated by tools/gen_game_data.py from the game's own ItemList (SystemData/ItemList). In each
// kingdom the purple-coin items add up to the kingdom's coin total (50 or 100).
export const SHOP_PRICES: readonly (readonly [list: string, name: string, purple: number, price: number, shop: number, clearFirst: number, moons: number])[] = [
''' + ''.join(f'  [{json.dumps(a)}, {json.dumps(b)}, {c}, {d}, {e}, {f}, {g}],\n' for a, b, c, d, e, f, g in prices) + '];\n')

# Power Moons needed to leave each kingdom (StageLockList): the list is flattened, one number per kingdom
# in the unlock order, which is the game's world index order.
needed = []
for entry in byml('StageLockList.byml')['StageLockList']:
    for moons in entry['ShineNumInfo']: needed.append((moons, int(entry.get('IsCountTotal', False))))
assert len(needed) == len(worlds)
(out / 'leave_catalog').mkdir(exist_ok=True)
(out / 'leave_catalog' / 'leave_moons.ts').write_text('''// Power Moons needed to leave each kingdom, by game world index: [moons, counted over all kingdoms].
// Where the second number is 1 the moons are counted over the whole game, not in that kingdom alone.
//
// Generated by tools/gen_game_data.py from the game's own StageLockList (SystemData/WorldList).
export const LEAVE_MOONS: readonly (readonly [moons: number, overall: number])[] = [
''' + ''.join(f'  [{a}, {b}], // {worlds[i]["WorldName"]}\n' for i, (a, b) in enumerate(needed)) + '];\n')
# The Power Moon each Crazy Cap shop hands out: the shop clerk's moon in the ShineList of its kingdom.
shop_moons = sorted(m['UniqueId'] for name in shine if name.startswith('ShineList_')
                    for m in szs.byml(shine[name])['ShineList'] if m['ObjectName'] == 'ショップ店員')
assert len(shop_moons) == 13, shop_moons
(out / 'moon_catalog' / 'shop_moons.ts').write_text('''// The Power Moons the Crazy Cap shops hand out when bought (one per kingdom that has a shop), by UniqueId.
// Buying one moves "Moons bought in shop" (ShopShine) of its kingdom.
//
// Generated by tools/gen_game_data.py from the game's own ShineList_* tables: the moon the shop clerk gives.
export const SHOP_MOONS: readonly number[] = [''' + ', '.join(map(str, shop_moons)) + '''];
''')
# ProgressBitFlag: bit (n - 1) set means the moon exists in scenario n of its kingdom; 0 means in every
# scenario. Moon Rock moons ignore it (they are tied to the Moon Rock scenario), so they are left out.
masks = sorted((m['UniqueId'], m['ProgressBitFlag']) for name in shine if name.startswith('ShineList_')
               for m in szs.byml(shine[name])['ShineList'] if m['ProgressBitFlag'] and not m['IsMoonRock'])
(out / 'moon_catalog' / 'moon_scenarios.ts').write_text('''// In which scenarios of its kingdom a Power Moon can be found: [UniqueId, bit mask]. Bit n - 1 set means the
// moon exists in scenario n. A moon that is not listed exists in every scenario (or, for a Moon Rock moon,
// is tied to the Moon Rock scenario).
//
// Generated by tools/gen_game_data.py from the ProgressBitFlag of the game's own ShineList_* tables; the game
// uses it in GameDataFile::HintInfo::isEnableUnlock (OdysseyDecomp, src/System/GameDataFile.cpp).
export const MOON_SCENARIOS: readonly (readonly [moon: number, mask: number])[] = [
''' + ''.join(f'  [{a}, {b}],\n' for a, b in masks) + '];\n')
# Official English texts of the stages (StageMessage): moon names ("ScenarioName_<ObjId>") and checkpoint
# names ("Checkpoint_<ObjId>"), one message file per stage.
messages = szs.sarc(szs.yaz0((root / 'LocalizedData' / 'USen' / 'MessageData' / 'StageMessage.szs').read_bytes()))
texts = {}
for file in messages:
    labels, strings = msbt.msbt(messages[file])
    texts[file[:-len('.msbt')]] = {labels[i]: strings[i].rstrip('\0') for i in labels}

moon_info = {}
for name in shine:
    if not name.startswith('ShineList_'): continue
    for m in szs.byml(shine[name])['ShineList']:
        moon_info[m['UniqueId']] = m
moons_path = out / 'moon_catalog' / 'moons.ts'
header = moons_path.read_text().split('export const MOONS')[0]
kept = {int(a): int(b) for a, b in re.findall(r'^\s*(\d+): \[".*?", (\d+)\]', moons_path.read_text(), re.M)}
official = {i: texts[m['StageName']]['ScenarioName_' + m['ObjId']] for i, m in moon_info.items()}
assert set(official) <= set(kept) | {i for i in official}, 'unknown moons'
rows = ''.join(f'  {i}: [{json.dumps(official[i], ensure_ascii=False)}, {kept[i]}],\n' for i in sorted(kept) if i in official)
moons_path.write_text(header + 'export const MOONS: Record<number, [name: string, kingdom: number]> = {\n' + rows + '};\n')

(out / 'moon_catalog' / 'moon_traits.ts').write_text('''// What kind of Power Moon some moons are: [UniqueId, Multi Moon (1/0), achievement moon (1/0), Moon Rock moon (1/0)].
// Only moons with at least one trait are listed.
//
// Generated by tools/gen_game_data.py from IsGrand, IsAchievement and IsMoonRock in the game's ShineList_* tables.
export const MOON_TRAITS: readonly (readonly [moon: number, multi: number, achievement: number, moonRock: number])[] = [
''' + ''.join(f'  [{i}, {int(m["IsGrand"])}, {int(m["IsAchievement"])}, {int(m["IsMoonRock"])}],\n' for i, m in sorted(moon_info.items()) if m['IsGrand'] or m['IsAchievement'] or m['IsMoonRock']) + '];\n')

checkpoints = sorted((stage_world[stage], stage, label[len('Checkpoint_'):], text) for stage, labels in texts.items() if stage in stage_world
                     for label, text in labels.items() if label.startswith('Checkpoint_'))
(out / 'checkpoint_catalog').mkdir(exist_ok=True)
(out / 'checkpoint_catalog' / 'checkpoints.ts').write_text('''// Every checkpoint flag of the game: [kingdom (game world index), stage, object ID, English name].
// The save keeps the ones reached in /Checkpoint as { StageName, ObjId }.
//
// Generated by tools/gen_game_data.py from the game's StageMessage ("Checkpoint_<ObjId>" texts).
export const CHECKPOINTS: readonly (readonly [kingdom: number, stage: string, obj: string, name: string])[] = [
''' + ''.join(f'  [{k}, {json.dumps(st)}, {json.dumps(o)}, {json.dumps(t, ensure_ascii=False)}],\n' for k, st, o, t in checkpoints) + '];\n')

hacks = [h['HackName'] for h in szs.byml(szs.sarc(szs.yaz0((root / 'SystemData' / 'HackObjList.szs').read_bytes()))['HackObjList.byml']) if not h.get('IsDebug')]
system = szs.sarc(szs.yaz0((root / 'LocalizedData' / 'USen' / 'MessageData' / 'SystemMessage.szs').read_bytes()))
def system_texts(name):
    labels, strings = msbt.msbt(system[name + '.msbt'])
    return {labels[i]: strings[i].rstrip('\0') for i in labels}
hack_names = system_texts('HackList')
(out / 'capture_catalog').mkdir(exist_ok=True)
(out / 'capture_catalog' / 'captures.ts').write_text('''// Everything Mario can capture: [name as the save keeps it in /HackDictionary, English name].
//
// Generated by tools/gen_game_data.py from the game's HackObjList (SystemData/HackObjList), without the debug
// entries, and the game's own HackList texts.
export const CAPTURES: readonly (readonly [id: string, name: string])[] = [
''' + ''.join(f'  [{json.dumps(h)}, {json.dumps(hack_names.get(h, h), ensure_ascii=False)}],\n' for h in hacks) + '];\n')

achievement_names, achievement_hints = system_texts('AchievementName'), system_texts('AchievementHint')
(out / 'achievement_catalog' / 'achievement_names.ts').write_text('''// The English name and the hint of each achievement, by its internal name in /AchievementSaveData.
//
// Generated by tools/gen_game_data.py from the game's AchievementName and AchievementHint texts.
export const ACHIEVEMENT_TEXTS: readonly (readonly [id: string, name: string, hint: string])[] = [
''' + ''.join(f'  [{json.dumps(k)}, {json.dumps(v, ensure_ascii=False)}, {json.dumps(achievement_hints.get(k, "").replace(chr(10), " "), ensure_ascii=False)}],\n' for k, v in sorted(achievement_names.items())) + '];\n')

bgm = system_texts('CollectBgmList')
(out / 'music_catalog').mkdir(exist_ok=True)
(out / 'music_catalog' / 'tracks.ts').write_text('''// The music tracks of the game's jukebox: [name as the save keeps it in /CollectBgmList, English title].
//
// Generated by tools/gen_game_data.py from the game's CollectBgmList texts.
export const TRACKS: readonly (readonly [id: string, title: string])[] = [
''' + ''.join(f'  [{json.dumps(k)}, {json.dumps(v, ensure_ascii=False)}],\n' for k, v in sorted(bgm.items(), key=lambda kv: kv[1].lower())) + '];\n')

visitable = ('ExStage', 'MoonExStage', 'PathwayStage', 'MoonFarSideExStage')
visits = sorted((index, stage['name'], stage['category']) for index, world in enumerate(worlds) for stage in world['StageList'] if stage.get('category') in visitable)
(out / 'stage_catalog' / 'visit_stages.ts').write_text('''// The stages the save can list as visited in /VisitStageData: [kingdom (game world index), stage, category].
// These are the side areas (ExStage, MoonExStage, PathwayStage, MoonFarSideExStage) of every kingdom.
//
// Generated by tools/gen_game_data.py from the game's WorldListFromDb (SystemData/WorldList).
export const VISIT_STAGES: readonly (readonly [kingdom: number, stage: string, category: string])[] = [
''' + ''.join(f'  [{k}, {json.dumps(n)}, {json.dumps(c)}],\n' for k, n, c in visits) + '];\n')

achievements = szs.byml(szs.sarc(szs.yaz0((root / 'SystemData' / 'AchievementInfo.szs').read_bytes()))['AchievementInfo.byml'])['AchievementInfoArray']
(out / 'achievement_catalog').mkdir(exist_ok=True)
(out / 'achievement_catalog' / 'achievement_goals.ts').write_text('''// How much each achievement asks for, by its internal name in /AchievementSaveData: [name, count].
// Only achievements that count something are listed (100 moons, 13 shops, ...).
//
// Generated by tools/gen_game_data.py from the game's AchievementInfo (SystemData/AchievementInfo).
export const ACHIEVEMENT_GOALS: readonly (readonly [name: string, count: number])[] = [
''' + ''.join(f'  [{json.dumps(a["Name"])}, {a["Num"]}],\n' for a in achievements if 'Num' in a) + '];\n')
# What kind of moon each one is, from the object that holds it (ObjectName in the ShineList). Only the kinds some
# achievement counts are named; every other moon has no kind.
KINDS = {
    'twod': ['シャインドット_2D'],
    'treasure': ['宝箱', '鍵付き宝箱', '順序宝箱'],
    'music': ['音符オブジェ(1つ目)', '音符オブジェ2D(1つ目)_2D', '音符オブジェ2D(1つ目)'],
    'timer': ['帽子掛け（タイマー）', '踏みスイッチ（タイマー）', '帽子スイッチ（タイマー）'],
    'toad': ['キノピオ隊長', '魚影_キノピオ隊長'],
    'peach': ['世界旅行ピーチ'],
    'sheep': ['コレクトアニマル監視者'],
    'goombette': ['ガールクリボー'],
    'seed': ['育つ草種'],
    'rabbit': ['ウサギ'],
    'dig': ['ここ掘れポイント', '忠犬専用ここ掘れポイント'],
    'caphanger': ['帽子ひっかけポイント'],
    'hintphoto': ['ヒント写真'],
    'hideseek': ['かくれんぼ帽子の民'],
    'shards': ['シャインチップ全取得監視者'],
}
kind_of = {name: kind for kind, names in KINDS.items() for name in names}
moon_kinds = sorted((i, kind_of[m['ObjectName']]) for i, m in moon_info.items() if m['ObjectName'] in kind_of)
(out / 'moon_catalog' / 'moon_kinds.ts').write_text('''// The kind of some Power Moons, by UniqueId: where or how the moon is found. Only the kinds an achievement counts
// are named (treasure chests, dig spots, music notes, ...).
//
// Generated by tools/gen_game_data.py from the object that holds each moon (ObjectName in the ShineList_* tables).
// Which achievement counts which kind is the editor's inference from the totals; see AchievementCatalog.
export const MOON_KINDS: readonly (readonly [moon: number, kind: string])[] = [
''' + ''.join(f'  [{i}, {json.dumps(k)}],\n' for i, k in moon_kinds) + '];\n')
print(f'wrote {len(runs)} coin runs for {len(ids)} coins, and {len(scenarios)} kingdoms of scenario data')
